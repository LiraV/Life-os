export const tipsOn = () => S.ui.tips === 'on';
export const tipSeen = key => !!S.ui.tipsSeen?.[key];

/** Карточка подсказки — или пусто, если подсказки выключены или уже видели. */
export function tipCard(key) {
  const tip = TIPS[key];
  if (!tip || !tipsOn() || tipSeen(key)) return '';
  return h`
    <div class="card tip">
      <div class="row between"><div class="caps">${tip.title}</div>
        <button class="q-edit" data-act="tipoff">не показывать</button></div>
      ${tip.lines.map(l => raw(h`<div class="lab">${l}</div>`))}
      <button class="pill" data-act="tipok" data-k="${key}">Понятно</button>
    </div>`;
}

export const tipActions = {
  tipok: v => update(s => { (s.ui.tipsSeen ||= {})[v.k] = true; }),
  tipoff: () => update(s => { s.ui.tips = 'off'; }),
};

/** Включить заново — и показать всё с чистого листа. */
export const tipsReset = () => update(s => { s.ui.tips = 'on'; s.ui.tipsSeen = {}; });
export const tipsDisable = () => update(s => { s.ui.tips = 'off'; });

/**
 * Предложение показывать подсказки. Приходит один раз: сразу после
 * онбординга у новых и при первом запуске новой версии у остальных.
 * Отказ запоминается — второй раз не спросим.
 */
export function offerTips() {
  if (!S.onboarded || S.ui.tips !== 'ask') return;
  openSheet({
    title: 'Показать, как всё устроено?',
    sub: 'коротко и по одному разу на экран',
    body: [
      `<p class="fld-note">На каждом экране будет карточка на три строки: что здесь делать и чего можно не бояться.
       Закрыла — больше не вернётся. Выключить всё разом можно в любой момент — в подсказке или в настройках.</p>`,
    ].join(''),
    primary: 'Показывать',
    onSave: (_v, close) => { update(s => { s.ui.tips = 'on'; s.ui.tipsSeen = {}; }); close(); },
    secondary: 'Обойдусь',
    onSecondary: (_v, close) => { update(s => { s.ui.tips = 'off'; }); close(); },
  });
}
