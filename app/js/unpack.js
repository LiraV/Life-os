const byKey = (list, key) => list.find(x => x.key === key) || list[0];

/**
 * Итог: ведущая сторона по каждой оси и та, что осталась последней в «из чего».
 * Слабую называем не приговором, а тем, что даётся дороже: писать об этом можно,
 * просто это будет стоить сил.
 */
export function unpackResult(picks) {
  const count = axis => {
    const out = {};
    UNPACK_Q.forEach((q, i) => {
      if (q.axis !== axis || !picks[i]) return;
      out[picks[i]] = (out[picks[i]] || 0) + 1;
    });
    return out;
  };
  const top = (axis, list) => {
    const c = count(axis);
    const sorted = list.map(x => [x.key, c[x.key] || 0]).sort((a, b) => b[1] - a[1]);
    return { first: sorted[0][0], last: sorted[sorted.length - 1][0], counts: c };
  };
  const w = top('well', WELLS), t = top('tone', TONES), f = top('form', FORMS);
  return {
    well: byKey(WELLS, w.first),
    weak: byKey(WELLS, w.last),
    tone: byKey(TONES, t.first),
    form: byKey(FORMS, f.first),
    counts: { well: w.counts, tone: t.counts, form: f.counts },
  };
}

