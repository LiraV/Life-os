/** Среднее по пунктам шкалы; rev — обратный пункт. */
const mean = (answers, items, dim, max) => {
  const picked = items.map((it, i) => ({ it, v: answers[i] })).filter(x => x.it.dim === dim);
  if (!picked.length) return 0;
  const sum = picked.reduce((a, x) => a + (x.it.rev ? max + 1 - x.v : x.v), 0);
  return sum / picked.length;
};

const lvl = (v, max) => (v >= max * 0.72 ? 'высоко' : v <= max * 0.44 ? 'низко' : 'посередине');

