/** Пункты теста в едином виде: у шкал — items, у опросников — questions. */
export const testLength = t => (t.kind === 'likert' ? (t.picks ? t.questions.length : t.items.length) : t.questions.length);

/** Посчитать результат по ответам. */
export function scoreTest(key, picks) {
  const t = TESTS[key];
  if (t.kind === 'pick') {
    const counts = {};
    picks.forEach(p => { counts[p] = (counts[p] || 0) + 1; });
    const top = Object.entries(counts).sort((a, b) => b[1] - a[1])[0][0];
    const res = t.results[top];
    return { title: res.text, lines: [], traitId: res.id, pickResult: top };
  }
  if (t.picks) return t.score(picks.reduce((a, x) => a + Number(x), 0));
  return t.score(picks.map(Number), t.items);
}
