export const BIZ_KIND_KEYS = BIZ_KINDS.map(k => k.key);
export const kindOf = key => BIZ_KINDS.find(k => k.key === key) || null;
export const kindName = key => kindOf(key)?.name || '';

/**
 * Шаги, без которых дело не выходит наружу: сначала свои для этого вида,
 * потом общие. Предлагаются по одному — ни один не появится сам.
 */
