export const practiceById = key => PRACTICES.find(p => p.key === key) || null;
export const practiceName = key => practiceById(key)?.name || key;

/** Длина одного круга дыхания в секундах. */
export const cycleSecs = p => (p.cycle || []).reduce((a, x) => a + x.secs, 0);

/**
 * Где мы внутри цикла на секунде t: фаза и сколько её осталось.
 * Возвращает и номер фазы — по нему видно, что она сменилась.
 */
export function phaseAt(p, t) {
  const len = cycleSecs(p);
  if (!len) return null;
  let rest = t % len;
  for (let i = 0; i < p.cycle.length; i++) {
    if (rest < p.cycle[i].secs) return { i, phase: p.cycle[i], left: p.cycle[i].secs - rest };
    rest -= p.cycle[i].secs;
  }
  return { i: 0, phase: p.cycle[0], left: p.cycle[0].secs };
}

/** Шаг практики-последовательности на секунде t. */
export function stepAt(p, t, total) {
  const per = total / p.steps.length;
  const i = Math.min(p.steps.length - 1, Math.floor(t / per));
  return { i, text: p.steps[i], left: Math.ceil(per * (i + 1) - t) };
}
