export const stageName = key => FREE_STAGES.find(s => s.key === key)?.name || '';
export const isPaid = o => o?.stage === 'paid';
export const isLost = o => o?.stage === 'lost';
/** Живой заказ — тот, что ещё в работе: ни оплачен, ни сорван. */
export const isLive = o => !isPaid(o) && !isLost(o);
/** Чистыми: цена минус комиссия площадки. Комиссия хранится у заказа —
 *  площадка может её поменять, а прошлые заказы от этого не должны поехать. */
export const netOf = o => Math.round((Number(o?.price) || 0) * (1 - (Number(o?.fee) || 0) / 100));
