/** Подходит ли дело этому человеку: пол, возраст, наличие питомца. */
export function fits(cond) {
  const yr = age();
  if (cond.sex && cond.sex !== S.user.sex) return false;
  // Возраст неизвестен — возрастные дела не предлагаем и не прячем молча:
  // они просто не всплывают, пока не заполнена дата рождения.
  if ((cond.from != null || cond.to != null) && yr == null) return false;
  if (cond.from != null && yr < cond.from) return false;
  if (cond.to != null && yr > cond.to) return false;
  if (cond.pet && !S.care.pet?.name) return false;
  return true;
}

/**
 * Что можно предложить: подходящее по профилю и ещё не заведённое.
 * Сравнение по названию — так повторно предложенное дело не задвоится,
 * даже если человек завёл его руками.
 */
export function careSuggestions() {
  const have = new Set((S.care.items || []).map(it => it.name.trim().toLowerCase()));
  return CARE_LIB
    .filter(([name, , , cond]) => fits(cond) && !have.has(name.toLowerCase()))
    .map(([name, group, every, cond], i) => ({ i, name, group, every, ...cond }));
}
