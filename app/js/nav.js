// Переходы между экранами. Отдельный модуль, потому что «назад» нужен экранам,
// а экраны нужны роутеру: импортируй они друг друга — вышло бы кольцо.

export const go = path => { location.hash = '#/' + path; };
export const route = () => location.hash.replace(/^#\/?/, '').split('/').filter(Boolean);

/**
 * Сколько шагов приложение прошло от места входа. Нужно ради «назад»: раньше
 * он ставил новый адрес, то есть *добавлял* шаг вместо того, чтобы снять. От
 * этого системная кнопка «назад» возвращала ровно туда, откуда человек только
 * что ушёл, — на телефоне с жестом «назад» это выводит из себя за минуту.
 *
 * Номер шага живёт в history.state: при движении вперёд его там ещё нет и мы
 * его проставляем, а на «назад» и «вперёд» браузер отдаёт сохранённый — по
 * нему и видно, есть ли куда возвращаться внутри приложения.
 */
let step = 0;

export function markStep() {
  if (history.state?.step != null) { step = history.state.step; return; }
  history.replaceState({ step: ++step }, '');
}

/** Место входа: с него «назад» ведёт из приложения, а не по кругу внутри него. */
export function startHere() { history.replaceState({ step: 0 }, ''); step = 0; }

/**
 * Вернуться туда, откуда пришли. Если приложение открыли сразу на этом экране
 * (ссылка, закладка, перезагрузка), возвращаться некуда — тогда ведём в
 * запасное место, обычно к сферам.
 */
export function goBack(fallback = 'spheres') {
  if (step > 0) history.back();
  else go(fallback);
}
