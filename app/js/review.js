// Недельный анализ состояния: анкета из восьми вопросов и двух открытых.
// Модуль без импортов — его тянут и хранилище, и селекторы, и экран.
//
// Пять делений, а не сто: анкету заполняют раз в неделю за минуту, и
// точность здесь не нужна — нужна повторяемость, чтобы ряды сравнивались.

/** Пять делений с подписями на краях — этого хватает, чтобы отвечать быстро. */
export const REVIEW_SCALE = [1, 2, 3, 4, 5];
export const REVIEW_ENDS = ['совсем нет', 'да, вполне'];

/**
 * Вопросы. Формулировки — про факт недели, а не про оценку себя: «высыпалась»,
 * а не «хорошо ли ты спала». Сторона у всех одна: больше — лучше, иначе ряды
 * не складываются в одно число.
 */
export const REVIEW_Q = [
  { key: 'sleep',  name: 'Сон',        q: 'Высыпалась на этой неделе' },
  { key: 'energy', name: 'Силы',       q: 'Сил хватало на то, что хотела' },
  { key: 'body',   name: 'Тело',       q: 'Тело чувствовалось хорошо' },
  { key: 'mood',   name: 'Настроение', q: 'Настроение держалось ровно' },
  { key: 'calm',   name: 'Спокойствие', q: 'Тревоги было немного' },
  { key: 'people', name: 'Люди',       q: 'Общения было столько, сколько нужно' },
  { key: 'work',   name: 'Дела',       q: 'Дела шли так, как я хотела' },
  { key: 'sense',  name: 'Смысл',      q: 'Понимала, зачем всё это' },
];

/** Открытые вопросы: одно, что забрало силы, и одно, что вернуло. */
export const REVIEW_OPEN = [
  { key: 'drain', q: 'Что забрало силы' },
  { key: 'fill',  q: 'Что вернуло силы' },
  { key: 'next',  q: 'Одно, что попробую на следующей неделе' },
];

/** Средний балл анкеты: 1–5. Незаполненные вопросы не считаются нулём. */
export function reviewScore(rec) {
  const vals = REVIEW_Q.map(q => Number(rec?.scores?.[q.key])).filter(v => v >= 1 && v <= 5);
  return vals.length ? Math.round((vals.reduce((a, b) => a + b, 0) / vals.length) * 10) / 10 : null;
}

/** Заполнена ли анкета — хотя бы один ответ по шкале. */
export const reviewFilled = rec => reviewScore(rec) != null;
