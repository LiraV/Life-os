// Род обращения. Приложение написано в женском роде — это его родной голос,
// поэтому женский вариант всегда идёт первым, а мужской подставляется.
//
// Ничего умного тут нет и не должно быть: русский род не выводится из правил
// без словаря, поэтому каждая форма записана руками там, где встречается.

import { S } from './store.js';

export const isMale = () => S.user.sex === 'm';

/** Пара форм: g('дочитала', 'дочитал'). Женская — первая. */
export const g = (fem, masc) => (isMale() ? masc : fem);

/** Формы на «-а»: gv('дочитал') → «дочитала» / «дочитал», gv('готов'), gv('сам'). */
export const gv = stem => (isMale() ? stem : stem + 'а');

/**
 * Род в готовом тексте: «сделал{а}» → «сделала» или «сделал». Если формы
 * расходятся сильнее суффикса, пишутся обе: «научил{ась|ся}».
 *
 * Нужен там, где текст лежит списком — подсказки, вопросы распаковки: их
 * нельзя собрать через g() в момент объявления, потому что род человек меняет
 * в настройках, а список читается один раз при загрузке. Подстановка делается
 * при показе, поэтому смена рода видна сразу.
 */
export const gt = s => String(s).replace(
  /\{([^}|]*)(?:\|([^}]*))?\}/g,
  (_, fem, masc = '') => (isMale() ? masc : fem),
);
